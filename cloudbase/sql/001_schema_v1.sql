-- 融智 Agent · CloudBase PostgreSQL 持久库 v1（结构）
-- 仅在 public schema 创建 rongzhi_bank_* 独立命名对象；不触碰其它项目对象。
-- 幂等：可重复执行，不删除、不清空、不覆盖既有数据。
-- 执行顺序：001_schema_v1.sql → 002_functions_v1.sql → 003_seed_v1.sql（仅首次演示数据）。

BEGIN;

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_users (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_accounts (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id               bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  account_name          text NOT NULL,
  opening_balance_cents bigint NOT NULL DEFAULT 0 CHECK (opening_balance_cents >= 0),
  balance_cents         bigint NOT NULL DEFAULT 0 CHECK (balance_cents >= 0),
  currency              text NOT NULL DEFAULT 'CNY',
  account_type          text NOT NULL DEFAULT 'deposit' CHECK (account_type IN ('deposit','credit')),
  status                text NOT NULL DEFAULT 'active' CHECK (status IN ('active','frozen','closed')),
  opened_on             text,
  created_at            timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_transactions (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  account_id     bigint NOT NULL REFERENCES public.rongzhi_bank_accounts(id),
  direction      text NOT NULL CHECK (direction IN ('income','expense')),
  amount_cents   bigint NOT NULL CHECK (amount_cents > 0),
  category       text NOT NULL,
  merchant       text,
  description    text,
  transaction_at timestamptz NOT NULL,
  posted_at      timestamptz,
  status         text NOT NULL DEFAULT 'posted' CHECK (status IN ('posted','pending')),
  transfer_ref   text,
  flow_kind      text NOT NULL DEFAULT 'external' CHECK (flow_kind IN ('external','repayment')),
  repayment_ref  text,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS rongzhi_bank_tx_transfer_ref_uq
  ON public.rongzhi_bank_transactions(transfer_ref) WHERE transfer_ref IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_cards (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  account_id         bigint NOT NULL REFERENCES public.rongzhi_bank_accounts(id),
  masked_card_number text NOT NULL,
  card_type          text NOT NULL,
  status             text NOT NULL DEFAULT 'active' CHECK (status IN ('active','frozen','cancelled')),
  daily_limit_cents  bigint NOT NULL DEFAULT 0 CHECK (daily_limit_cents >= 0),
  issued_on          text,
  version            integer NOT NULL DEFAULT 1,
  created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_subscriptions (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  account_id        bigint NOT NULL REFERENCES public.rongzhi_bank_accounts(id),
  merchant          text NOT NULL,
  amount_cents      bigint NOT NULL CHECK (amount_cents > 0),
  billing_cycle     text NOT NULL CHECK (billing_cycle IN ('monthly','yearly')),
  next_billing_date text,
  status            text NOT NULL DEFAULT 'active' CHECK (status IN ('active','paused','cancelled')),
  version           integer NOT NULL DEFAULT 1,
  created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_audit_logs (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        bigint,
  operation_type text NOT NULL,
  operation_ref  text,
  action         text NOT NULL,
  result         text,
  detail         jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_transfer_recipients (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  masked_account text NOT NULL,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_transfer_operations (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no                   text NOT NULL UNIQUE,
  user_id                  bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  session_id               text,
  from_account_id          bigint NOT NULL REFERENCES public.rongzhi_bank_accounts(id),
  from_account_name        text NOT NULL,
  recipient_id             bigint NOT NULL REFERENCES public.rongzhi_bank_transfer_recipients(id),
  recipient_name           text NOT NULL,
  recipient_masked_account text NOT NULL,
  amount_cents             bigint NOT NULL CHECK (amount_cents > 0),
  remark                   text,
  status                   text NOT NULL DEFAULT 'pending'
                             CHECK (status IN ('pending','needs_verification','completed','cancelled','expired','failed')),
  risk_level               text NOT NULL CHECK (risk_level IN ('yellow','red')),
  created_at               timestamptz NOT NULL DEFAULT now(),
  expires_at               timestamptz NOT NULL,
  confirmed_at             timestamptz
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_card_operations (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no       text NOT NULL UNIQUE,
  user_id      bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  card_id      bigint NOT NULL REFERENCES public.rongzhi_bank_cards(id),
  card_masked  text NOT NULL,
  card_type    text NOT NULL,
  action       text NOT NULL CHECK (action IN ('freeze','unfreeze')),
  from_status  text NOT NULL,
  to_status    text NOT NULL,
  card_version integer NOT NULL,
  risk_level   text NOT NULL CHECK (risk_level IN ('yellow','red')),
  status       text NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending','needs_verification','completed','cancelled','expired','failed')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  expires_at   timestamptz NOT NULL,
  confirmed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_subscription_operations (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no                text NOT NULL UNIQUE,
  user_id               bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  subscription_id       bigint NOT NULL REFERENCES public.rongzhi_bank_subscriptions(id),
  merchant              text NOT NULL,
  amount_cents          bigint NOT NULL,
  billing_cycle         text NOT NULL,
  action                text NOT NULL CHECK (action IN ('pause','resume','cancel','change_source')),
  from_status           text NOT NULL,
  to_status             text NOT NULL,
  subscription_version  integer NOT NULL,
  from_account_id       bigint REFERENCES public.rongzhi_bank_accounts(id),
  from_account_name     text,
  from_account_type     text,
  from_masked_card      text,
  to_account_id         bigint REFERENCES public.rongzhi_bank_accounts(id),
  to_account_name       text,
  to_account_type       text,
  to_masked_card        text,
  risk_level            text NOT NULL CHECK (risk_level IN ('yellow','red')),
  status                text NOT NULL DEFAULT 'pending'
                          CHECK (status IN ('pending','needs_verification','completed','cancelled','expired','failed')),
  created_at            timestamptz NOT NULL DEFAULT now(),
  expires_at            timestamptz NOT NULL,
  confirmed_at          timestamptz
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_verification_bindings (
  user_id         bigint PRIMARY KEY REFERENCES public.rongzhi_bank_users(id),
  password_salt   text NOT NULL,
  password_hash   text NOT NULL,
  totp_secret_enc jsonb NOT NULL,
  enabled         integer NOT NULL DEFAULT 1,
  bound_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_totp_used_steps (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  step        bigint NOT NULL,
  purpose     text NOT NULL,
  consumed_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (user_id, step)
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_verification_failures (
  user_id      bigint PRIMARY KEY REFERENCES public.rongzhi_bank_users(id),
  fail_count   integer NOT NULL DEFAULT 0,
  locked_until timestamptz
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_chat_sessions (
  id                          text PRIMARY KEY,
  user_id                     bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  messages_json               jsonb NOT NULL DEFAULT '[]'::jsonb,
  pending_transfer_ref        text,
  pending_card_op_ref         text,
  pending_subscription_op_ref text,
  pending_repayment_ref       text,
  created_at                  bigint NOT NULL,
  last_active_at              bigint NOT NULL,
  version                     bigint NOT NULL DEFAULT 0,
  last_turn_id                text
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_chat_messages (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id        text NOT NULL REFERENCES public.rongzhi_bank_chat_sessions(id),
  user_id           bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  seq               integer NOT NULL,
  role              text NOT NULL CHECK (role IN ('user','assistant')),
  text              text NOT NULL,
  tool_records_json jsonb,
  incomplete        integer NOT NULL DEFAULT 0,
  error             text,
  created_at        bigint NOT NULL,
  turn_id           text
);
CREATE UNIQUE INDEX IF NOT EXISTS rongzhi_bank_chat_msg_turn_uq
  ON public.rongzhi_bank_chat_messages(session_id, turn_id, role)
  WHERE turn_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_chat_state (
  user_id            bigint PRIMARY KEY REFERENCES public.rongzhi_bank_users(id),
  current_session_id text
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_agent_tasks (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_no                  text NOT NULL UNIQUE,
  user_id                  bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  kind                     text NOT NULL DEFAULT 'subscription_review' CHECK (kind IN ('subscription_review')),
  status                   text NOT NULL DEFAULT 'waiting_selection'
                             CHECK (status IN ('waiting_selection','waiting_confirmation','completed','failed','paused','cancelled','manual')),
  month                    text,
  session_id               text,
  selected_subscription_id bigint REFERENCES public.rongzhi_bank_subscriptions(id),
  op_ref                   text,
  result_summary           jsonb,
  failure_reason           text,
  created_at               bigint NOT NULL,
  updated_at               bigint NOT NULL,
  completed_at             bigint
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_agent_task_nodes (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id      bigint NOT NULL REFERENCES public.rongzhi_bank_agent_tasks(id),
  node_key     text NOT NULL,
  seq          integer NOT NULL,
  status       text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','completed','failed','skipped')),
  depends_on   jsonb,
  result_json  jsonb,
  error        text,
  started_at   bigint,
  completed_at bigint,
  UNIQUE (task_id, node_key)
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_credit_accounts (
  id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                  bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  account_id               bigint NOT NULL UNIQUE REFERENCES public.rongzhi_bank_accounts(id),
  credit_limit_cents       bigint NOT NULL CHECK (credit_limit_cents > 0),
  posted_outstanding_cents bigint NOT NULL DEFAULT 0 CHECK (posted_outstanding_cents >= 0),
  pending_occupied_cents   bigint NOT NULL DEFAULT 0 CHECK (pending_occupied_cents >= 0),
  version                  integer NOT NULL DEFAULT 1,
  created_at               timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_statements (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  credit_account_id bigint NOT NULL REFERENCES public.rongzhi_bank_credit_accounts(id),
  statement_year    integer NOT NULL,
  statement_month   integer NOT NULL,
  period_start      timestamptz NOT NULL,
  period_end        timestamptz NOT NULL,
  issued_on         timestamptz NOT NULL,
  issued_at         timestamptz,
  due_on            timestamptz NOT NULL,
  new_charges_cents bigint NOT NULL DEFAULT 0 CHECK (new_charges_cents >= 0),
  paid_cents        bigint NOT NULL DEFAULT 0 CHECK (paid_cents >= 0),
  version           integer NOT NULL DEFAULT 1,
  created_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (credit_account_id, statement_year, statement_month)
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_statement_payments (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  statement_id  bigint NOT NULL REFERENCES public.rongzhi_bank_statements(id),
  repayment_ref text NOT NULL,
  amount_cents  bigint NOT NULL CHECK (amount_cents > 0),
  paid_at       timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_repayment_allocations (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no            text NOT NULL,
  statement_id      bigint NOT NULL REFERENCES public.rongzhi_bank_statements(id),
  amount_cents      bigint NOT NULL CHECK (amount_cents > 0),
  statement_version integer NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  UNIQUE (ref_no, statement_id)
);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_repayment_operations (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ref_no              text NOT NULL UNIQUE,
  user_id             bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  session_id          text,
  scope               text NOT NULL DEFAULT 'statement' CHECK (scope IN ('statement','all_posted')),
  from_account_id     bigint NOT NULL REFERENCES public.rongzhi_bank_accounts(id),
  from_account_name   text NOT NULL,
  credit_account_id   bigint NOT NULL REFERENCES public.rongzhi_bank_credit_accounts(id),
  credit_account_name text NOT NULL,
  statement_id        bigint NOT NULL REFERENCES public.rongzhi_bank_statements(id),
  statement_month     text NOT NULL,
  amount_cents        bigint NOT NULL CHECK (amount_cents > 0),
  statement_version   integer NOT NULL,
  risk_level          text NOT NULL CHECK (risk_level = 'red'),
  status              text NOT NULL DEFAULT 'needs_verification'
                        CHECK (status IN ('needs_verification','completed','cancelled','expired','failed')),
  created_at          timestamptz NOT NULL DEFAULT now(),
  expires_at          timestamptz NOT NULL,
  confirmed_at        timestamptz
);

CREATE INDEX IF NOT EXISTS rongzhi_bank_accounts_user_idx ON public.rongzhi_bank_accounts(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_tx_user_idx ON public.rongzhi_bank_transactions(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_tx_account_idx ON public.rongzhi_bank_transactions(account_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_tx_time_idx ON public.rongzhi_bank_transactions(transaction_at);
CREATE INDEX IF NOT EXISTS rongzhi_bank_cards_user_idx ON public.rongzhi_bank_cards(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_subs_user_idx ON public.rongzhi_bank_subscriptions(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_transfer_user_idx ON public.rongzhi_bank_transfer_operations(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_cardop_user_idx ON public.rongzhi_bank_card_operations(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_subop_user_idx ON public.rongzhi_bank_subscription_operations(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_repay_user_idx ON public.rongzhi_bank_repayment_operations(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_chat_msg_session_idx ON public.rongzhi_bank_chat_messages(session_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_task_user_idx ON public.rongzhi_bank_agent_tasks(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_tasknode_task_idx ON public.rongzhi_bank_agent_task_nodes(task_id);

COMMIT;
