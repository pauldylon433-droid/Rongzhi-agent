BEGIN;

ALTER TABLE public.rongzhi_bank_chat_sessions
  ADD COLUMN IF NOT EXISTS version bigint NOT NULL DEFAULT 0;
ALTER TABLE public.rongzhi_bank_chat_sessions
  ADD COLUMN IF NOT EXISTS last_turn_id text;
ALTER TABLE public.rongzhi_bank_chat_messages
  ADD COLUMN IF NOT EXISTS turn_id text;

CREATE UNIQUE INDEX IF NOT EXISTS rongzhi_bank_chat_msg_turn_uq
  ON public.rongzhi_bank_chat_messages(session_id, turn_id, role)
  WHERE turn_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_audit_events (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id      text NOT NULL UNIQUE,
  user_id       bigint REFERENCES public.rongzhi_bank_users(id),
  request_id    text,
  session_id    text,
  plan_id       text,
  tool_call_id  text,
  operation_ref text,
  category      text NOT NULL,
  action        text NOT NULL,
  result        text,
  risk_level    text,
  detail        jsonb,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rongzhi_bank_audit_events_request_idx ON public.rongzhi_bank_audit_events(request_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_audit_events_session_idx ON public.rongzhi_bank_audit_events(session_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_audit_events_plan_idx ON public.rongzhi_bank_audit_events(plan_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_audit_events_op_idx ON public.rongzhi_bank_audit_events(operation_ref);
CREATE INDEX IF NOT EXISTS rongzhi_bank_audit_events_created_idx ON public.rongzhi_bank_audit_events(created_at);

CREATE TABLE IF NOT EXISTS public.rongzhi_bank_workflow_plans (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_no      text NOT NULL UNIQUE,
  user_id      bigint NOT NULL REFERENCES public.rongzhi_bank_users(id),
  flow         text NOT NULL CHECK (flow IN ('subscription_review','repayment_review')),
  status       text NOT NULL,
  plan_json    jsonb NOT NULL,
  version      bigint NOT NULL DEFAULT 0,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);
CREATE INDEX IF NOT EXISTS rongzhi_bank_workflow_plans_user_idx ON public.rongzhi_bank_workflow_plans(user_id);
CREATE INDEX IF NOT EXISTS rongzhi_bank_workflow_plans_status_idx ON public.rongzhi_bank_workflow_plans(status);

COMMIT;
